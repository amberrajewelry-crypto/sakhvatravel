LANG_PATH = {"ru": "{c}/index.html", "en": "en/{c}/index.html", "ka": "ge/{c}/index.html"}


def enrich(path, items):
    full = os.path.join(ROOT, path)
    if not os.path.exists(full):
        return None
    h = open(full, encoding="utf-8").read()
    add = ""
    for q, a in items:
        if q in h:
            continue
        add += "\n" + FI.format(q=q, a=a)
    if not add:
        return 0
    # insert before the FAQ container's closing </div> that precedes other-regions
    m = re.search(r'(</div>)(\s*<div class="other-regions">)', h)
    if not m:
        return -1
    new = h[:m.start(1)] + add + "\n" + h[m.start(1):]
    if APPLY:
        open(full, "w", encoding="utf-8").write(new)
    return len(items)


def main():
    tot = 0; errs = []
    for c, langs in C.items():
        for lang, items in langs.items():
            path = LANG_PATH[lang].format(c=c)
            r = enrich(path, items)
            if r is None:
                errs.append(f"NO FILE {path}")
            elif r == -1:
                errs.append(f"NO ANCHOR {path}")
            elif r == 0:
                print(f"  skip (already) {path}")
            else:
                tot += 1
                print(f"  +{r} FAQ  {path}")
    print(f"\n{'APPLIED' if APPLY else 'DRY'} — стран-страниц обновлено: {tot}")
    for e in errs:
        print("  ERR", e)


if __name__ == "__main__":
    main()
