LANG_PATH = {"ru": "{c}/index.html", "en": "en/{c}/index.html", "ka": "ge/{c}/index.html"}


def enrich(path, items):
    full = os.path.join(ROOT, path)
    if not os.path.exists(full):
        return None
    h = open(full, encoding="utf-8").read()
    add = "".join("\n" + FI.format(q=q, a=a) for q, a in items if q not in h)
    if not add:
        return 0
    m = re.search(r'(</div>)(\s*<div class="other-regions">)', h)
    if not m:
        return -1
    new = h[:m.start(1)] + add + "\n" + h[m.start(1):]
    if APPLY:
        open(full, "w", encoding="utf-8").write(new)
    return sum(1 for q, _ in items if q not in h)


def main():
    tot = 0
    for c, langs in C.items():
        for lang, items in langs.items():
            path = LANG_PATH[lang].format(c=c)
            r = enrich(path, items)
            print(f"  {('+'+str(r)) if r and r>0 else 'skip' if r==0 else 'ERR'}  {path}")
            if r and r > 0:
                tot += 1
    print(f"\n{'APPLIED' if APPLY else 'DRY'} — обновлено: {tot}")


if __name__ == "__main__":
    main()
